module C = Discovery.Catalog
module H = Pc.Harness

let check condition message = if not condition then failwith message

let with_file contents f =
  let path = Filename.temp_file "pc-unit-" ".tmp" in
  Fun.protect ~finally:(fun () -> Sys.remove path) (fun () ->
    let oc = open_out_bin path in output_string oc contents; close_out oc; f path)

let read path =
  let ic = open_in_bin path in
  Fun.protect ~finally:(fun () -> close_in_noerr ic) (fun () -> really_input_string ic (in_channel_length ic))

let rejected f =
  match f () with
  | _ -> failwith "expected catalog rejection"
  | exception C.Invalid _ -> ()

let () =
  let path = Sys.argv.(1) in
  let catalog = C.load path in
  check (List.length catalog = 112) "catalog count";
  let data = read path in
  let lines = String.split_on_char '\n' data |> List.filter ((<>) "") in
  let header = List.hd lines and rows = List.tl lines in
  let load_lines xs f = with_file (String.concat "\n" xs ^ "\n") f in
  List.iter (fun xs -> load_lines xs (fun p -> rejected (fun () -> C.load p)))
    [["wrong header"]; header :: List.tl rows; header :: List.hd rows :: rows];
  let change column value row =
    String.split_on_char '\t' row |> List.mapi (fun i field -> if i = column then value else field)
    |> String.concat "\t" in
  List.iter (fun (column,value) ->
    let mutated = header :: change column value (List.hd rows) :: List.tl rows in
    load_lines mutated (fun p -> rejected (fun () -> C.load p)))
    [0,"0"; 0,"15"; 0,"01"; 1,"9"; 2,"1.8.1"; 3,"110102";
     4,"0"; 4,"10189"; 5,""; 5," padded"; 5,"bad\rtitle"; 5,"bad\000title"];
  let gen = C.generate ~root:"solutions" catalog in
  let a = "solutions/ch01/p01.ml" and b = "solutions/ch14/p08.ml" in
  check (gen [a;b] = gen [b;a]) "source order must not change generated bytes";
  load_lines (header :: List.rev rows) (fun p ->
    check (C.generate ~root:"solutions" (C.load p) [b;a] = gen [a;b]) "catalog order determinism");
  List.iter (fun sources -> rejected (fun () -> gen sources))
    [[a;a]; ["solutions/p01.ml"]; ["solutions/ch1/p01.ml"]; ["solutions/ch01/p1.ml"];
     ["solutions/ch01/p00.ml"]; ["solutions/ch15/p01.ml"]; ["solutions/ch01/p09.ml"];
     ["solutions/ch01/nested/p01.ml"]; ["other/ch01/p01.ml"]; ["solutions/ch+1/p01.ml"]];
  let title = "Quote \" and \\ and UTF-8: ö" in
  load_lines (header :: change 5 title (List.hd rows) :: List.tl rows) (fun path ->
    let text = C.generate ~root:"solutions" (C.load path) [] in
    let literal = Printf.sprintf "title = %S" title in
    let contains text pattern =
      let rec loop i = i + String.length pattern <= String.length text &&
        (String.sub text i (String.length pattern) = pattern || loop (i+1)) in loop 0 in
    check (contains text literal) "escaped OCaml string literal");
  let all = Problem_registry.Registry.all in
  List.iter (fun id -> check ((H.find all id).pc_id = "110101") ("alias " ^ id))
    ["1.6.1"; "110101"; "pc:110101"; "uva:100"];
  List.iter (fun id ->
    match H.find all id with _ -> failwith ("unexpected alias: " ^ id) | exception H.Invalid _ -> ())
    ["100"; "uva:110101"; "1.6.9"; ""];
  List.iter (fun (expected,actual,offset) ->
    with_file expected (fun e -> with_file actual (fun a ->
      match H.compare_files e a, offset with
      | None, None -> ()
      | Some d, Some n -> check (d.offset = n) "first differing byte"
      | _ -> failwith "exact comparison")))
    ["","",None; "a\n","a\n",None; "a\n","a",Some 1; "a","a\n",Some 1;
     "a b\n","a\tb\n",Some 1; "\000\255","\000\254",Some 1;
     String.make 10000 'a',String.make 10000 'a' ^ "x",Some 10000];
  print_endline "catalog, generation, aliases, and byte comparison: passed"
